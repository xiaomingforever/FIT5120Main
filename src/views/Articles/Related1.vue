        <h1 id="article-title" class="title">6 Key Nutrients Kids Need: A Guide by Age</h1>

        <p class="dek">
          Here's what to know about the top nutrients your kids need from infancy through the teen
          years.
        </p>

        <p class="byline">
          <span class="author">By Rachel Meltzer Warren, M.S., R.D. </span>
          <span class="divider" aria-hidden="true">|</span>
          <time class="date" datetime="2024-05-01">May 1, 2024</time>
        </p>
