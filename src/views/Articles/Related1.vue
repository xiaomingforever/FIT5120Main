      <article class="copy">
        <p>
          Making sure you know the right nutrients for kids—and ensuring they get those
          nutrients—will help your little ones learn, grow, and develop. For many, this simply
          involves breastfeeding or formula-feeding in infancy, followed by eating a varied and
          balanced diet in the toddler years and beyond. But for kids with extreme pickiness or
          health issues that impact their ability to eat or use nutrients, supplements—or even a
          feeding tube—could be required to stay well nourished. Your pediatrician, along with a
          pediatric registered dietitian nutritionist (RDN), can help you understand your child's
          unique nutritional requirements. They also can advise you on what tools you can use to
          help them get the vitamins and minerals their bodies need to thrive. But, as a general
          rule, here are the top nutrients for kids at every age.
        </p>
        <h2>Are Your Kids Consuming Enough of These Essential Nutrients?</h2>
        <p>
          While kids need numerous vitamins and minerals, six key nutrients are especially important
          to be getting daily. These include vitamin D, iron, omega-3s, zinc, calcium, and
          potassium. Here's how to ensure your child is consistently getting these nutrients.
        </p>
        <h2>Vitamin D</h2>
        <p>
          Vitamin D supports bone health at all ages. In the early years, it helps build strong
          bones that benefit kids for life. It also reduces inflammation and improves immunity.
          While we can get vitamin D from food and supplements, our bodies also produce vitamin D
          from sunlight exposure. Those with darker skin and people who don't get a lot of natural
          sunlight may be more likely to need vitamin D from sources other than the sun. Vitamin D
          is found in trout, salmon, vitamin D-fortified milk, plant-based milk, and fortified
          cereal.
        </p>
        <p>
          0-6 months: Shortly after birth, infants fed human milk—as well as formula-fed infants who
          consume less than 27 ounces of formula per day—need to be started on a vitamin D
          supplement that provides at least 400 IU per day, says Amy Reed, MS, RD, a pediatric
          dietitian at Cincinnati Children's Hospital Medical Center. "In the first 6 months of
          life, human milk can provide all nutrient needs except for Vitamin D."
        </p>
        <p>
          Infants: Because it can be difficult to get enough vitamin D from food sources, Reeds says
          infants older than 6 months may continue to need a supplement. Talk to your child's
          pediatrician to see what is best for your child. Again, children younger than 12 months
          need 400 IU per day, says the CDC, and this increases to 600 mg after 12 months.
        </p>
        <p>
          Toddlers and young children: As kids get older, they typically eat more foods that contain
          vitamin D. As a result, they may not need a supplement, says Reed. However, it's still a
          good idea to talk to your child's pediatrician to understand their needs
        </p>
        <p>
          Older children and teenagers: The recommended amount of vitamin D is 600 IU per day, but
          older children will sometimes get their vitamin D level checked to ensure they're getting
          enough. If your provider finds your child's vitamin D level is low, they may recommend
          supplementation.
        </p>
        <h2>Iron</h2>
        <p>
          This mineral carries oxygen in the red blood cells to help the body produce energy. When
          iron levels are low, a person may feel weak or tired. Babies in particular need iron for
          brain development and growth. Iron is found in meat, seafood, poultry, spinach, beans, and
          fortified cereals. Eating iron-containing foods with a source of vitamin C like citrus
          fruit, broccoli, and red bell peppers can help increase your child's iron absorption.
        </p>
        <p>
          0-6 months: Most newborns have gained enough iron stores for about the first 6 months of
          life.
        </p>
        <p>
          Infants: At 6 months, your child's iron needs increase from 0.27 mg per day to 11 mg per
          day, says Reed. This is the perfect time to introduce foods that are good sources of iron
          like iron-fortified cereals, meats, and beans. Iron deficiency can lead to slower
          development and physical symptoms like irritability and slow weight gain.
        </p>
        <P>
          Toddlers and young children: Between the ages of 1 and 3, your child needs 7 mg per day,
          and 10 mg per day between the ages of 4 and 8. Too much cow's milk at this age can crowd
          out other foods, resulting in a child not getting enough iron, says Reed. Limit your
          little one to no more than 20 ounces of cow's milk per day once they reach toddlerhood.
        </P>
        <p>
          Older children and teenagers: Keep in mind that, around age 9, kids often start to
          decrease their intake of protein-rich foods that are also good sources of iron. But iron
          continues to be important for healthy development—especially for teenage girls who
          experience monthly blood loss from menstruation, says Reed.
        </p>
        <h2>Omega-3s</h2>
        <p>
          Omega 3s are an essential fatty acid, and they're especially important for kids' brain
          health, says Marina Chaparro, MPH, RDN, a diabetes educator and founder of Nutrichicos, a
          bilingual pediatric nutrition practice in Miami. They're one of the key nutrients needed
          for the rapid brain development that happens in the first 2 years of life, says Chaparro.
          After the first 2 years, omega-3s remain important for the central nervous and
          cardiovascular systems, as well as healthy eye function. You can find omega 3s in salmon,
          sardines, herring, mackerel, walnuts, flaxseeds, chia seeds, and canola oil.
        </p>
        <p>
          0-6 months: Human milk contains the omega-3 known as DHA, as do most commercial infant
          formulas. Other sources include ALA (mostly found in plants) and EPA. From 0 to 12 months,
          your baby needs 0.5 grams of omega-3 per day.
        </p>
        <P>
          Infants: Babies this age will still get some omega-3s through human milk and formula.
          Introducing foods like fish and muffins baked with flaxseed can help them develop a taste
          for foods that include omega-3s as well.
        </P>
        <P>
          Toddlers and young children: From 1 to 3 years, your little one needs 0.7 grams per day.
          And between 4 and 8 years it increases to 0.9 grams per day. Snacking on chia pudding,
          adding flaxseed oil to smoothies, and having salmon burgers for dinner are all
          kid-friendly ways of getting in omega-3s.
        </P>
        <P>
          Older children and teenagers: After 9 years of age, your child's need for omega-3s
          increases to more than 1 to 1.6 grams per day. Continue to look for ways to add omega-3s
          to their diet.
        </P>
        <h2>Zinc</h2>
        <P>
          This mineral is required for healthy growth and development. The immune system, in
          particular, needs zinc to function and to help with wound healing. It also plays a role in
          the sense of taste and smell. Zinc is available in meats, dairy, fish, shellfish, legumes,
          and fortified cereals.
        </P>
        <P>
          0-6 months: At this age, human milk and formula provide an adequate amount of zinc.
          However, if you are concerned about your child's intake, discuss their nutrition with
          their pediatrician. Babies 0-6 months need 2 mg per day.
        </P>
        <P>
          Infants: According to Reed, the amount of zinc in human milk can decrease, says Reed. If
          your baby is mostly consuming human milk, be sure to offer complementary foods that are
          good sources of zinc starting at 6 months of age. Babies aged 7–12 months need 3 mg of
          zinc per day.
        </P>
        <P>
          Toddlers and young children: If your child has a varied diet, they will typically eat
          enough zinc, says Reed. "But, if children are vegetarian, they may need to consume higher
          amounts of plant-based sources of zinc or zinc-fortified grains to achieve adequate
          intake." Kids ages 1–3 years need 7 mg daily, and those 4–8 years require 12 mg.
        </P>
        <P>
          Older children and teenagers: While adequate zinc intake is still important, it was not
          identified as a nutrient concern for this age group by the 2020-2025 U.S. Dietary
          Guidelines, says Reed.10 Dietary Guidelines for Americans, 2020-2025. U.S. Department of
          Agriculture. 2020. However, you can always talk to a health care provider if you have
          concerns.
        </P>
        <h2>Calcium</h2>
        <P>
          While calcium plays a variety of roles in the body, it's best known for helping build
          strong bones and teeth. Up to 90% of your child's peak bone mass will be built before they
          hit their 20s—meaning the early years are the most important time to build bone density.
          Cow's milk, yogurt, cheese, almonds, broccoli, kale, spinach, and fortified plant-based
          milk are all good sources of calcium.
        </P>
        <P>
          0-6 months: Babies at this age get the calcium they need through human milk or formula. If
          you are concerned about your baby's intake of human milk or formula, make sure you talk to
          your child's pediatrician.
        </P>
        <P>
          Infants: Your baby's calcium needs increase after 6 months. However, children under 1 year
          of age should still not drink cow's milk to meet those needs. The calcium in human milk
          and formula, as well as complementary foods that are appropriate for this age like yogurt,
          tofu, and broccoli, can help meet those needs.
        </P>
        <P>
          Toddlers and young children: At ages 1-3, children need 700 mg of calcium per day—and this
          increases to 1,000 mg for those ages 4-8, says Reed. Cow's milk is one possible source
          since it contains 300 mg of calcium per eight-ounce glass. But drinking milk isn't
          necessary—calcium is also available in foods like cheese and yogurt, as well as non-dairy
          sources like leafy greens, almonds, fortified plant-based milks, and tofu.
        </P>
        <P>
          Older children and teenagers: Calcium is especially important at this age because it's
          when your child's body is storing calcium to ensure strong bones for decades to come. At
          age 9, the recommended calcium intake increases from 1,000 to 1,300 mg per day. "This is
          also the age that intake of dairy foods decreases," says Reed.
        </P>
        <h2>Potassium</h2>
        <P>
          This electrolyte mineral helps nerves to function and muscles to contract, and it plays a
          role in ensuring your heartbeat stays regular. It also helps maintain normal levels of
          fluid inside our cells and can flush sodium from the body, counteracting some of that
          mineral's harmful effects on blood pressure. Most of the time, a balanced diet is enough
          to maintain healthy potassium levels. However, if your child loses fluid through vomiting
          or diarrhea, talk to your pediatrician about how to meet their increased needs for this
          electrolyte. Potassium is found in oranges, grapefruits, melons, grapes, spinach,
          potatoes, bananas, lentils, dried fruit, winter squash, sweet potatoes, and milk.
        </P>
        <P>
          0-6 months: Human milk and infant formula should contain the right balance of potassium
          for a baby this age; they need 400 mg per day. As always, though, talk to your child's
          pediatrician if they are vomiting or have diarrhea. They may ask you to increase feedings
          to meet their needs.
        </P>
        <P>
          Infants: According to the 2020-2025 Dietary Guidelines for Americans, potassium is a
          nutrient of concern for older infants, who need about 860 mg daily.10 As you add in
          supplementary foods, be sure you are including plenty of produce—bananas, melons, and
          oranges are all good sources of potassium that can be safely introduced at this age.
        </P>
        <P>
          Toddlers and young children: Potassium continues to be an important nutrient at this age.
          Fruits and vegetables are important sources. However, whole grains and dairy foods which
          are part of a balanced diet also provide potassium. Potassium needs range from 2,000 mg
          for ages 1-3 to 2,300 mg for ages 4-8.
        </P>
        <P>
          Older children and teenagers: This mineral is crucial for very active kids who are losing
          sweat, says Chaparro. Eating and drinking foods high in potassium helps maintain proper
          fluid balance, she says, especially during periods of high activity or hot weather.
        </P>
