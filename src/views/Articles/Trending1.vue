        <h1 id="article-title" class="title">24 Brain Breaks for Kids To Try at Home</h1>

        <p class="dek">
          These short, fun activities can help kids recharge and refocus when school or homework is
          stressing them out.
        </p>

        <p class="byline">
          <span class="author">By Catherine Holecko </span>
          <span class="divider" aria-hidden="true">|</span>
